import assert from 'node:assert/strict';
import {scheduleDays,vietnamDate,attendanceReminders} from '../src/attendance-reminders.ts';
for(const input of ['Thứ 2, 4, 6','T2-T4-T6','Thứ hai, thứ tư và thứ sáu'])assert.deepEqual(scheduleDays(input),[2,4,6]);
assert.deepEqual(scheduleDays('Thứ 3 / 5 / 7 & CN'),[3,5,7,8]);
assert.deepEqual(scheduleDays('Thứ 2 đến thứ 6'),[2,3,4,5,6]);
assert.deepEqual(scheduleDays('Chủ nhật'),[8]);assert.deepEqual(scheduleDays('Hằng ngày'),[2,3,4,5,6,7,8]);
for(const input of ['',null,'17:00 - 18:30','Thứ 9','2026-11-03','Thứ 2 abc'])assert.equal(scheduleDays(input),null);
const cls=(id,days,extra={})=>({id,kind:'class',data:{name:id,days,...extra}});
const rows=[cls('A','Thứ 3,5,7',{time:'17:00'}),cls('B','Thứ 3',{time:'8:00'}),cls('C','Thứ 2,4,6'),cls('D','Thứ 3',{deleted:true}),cls('E','')];
const owner={isSuperAdmin:true},tuesday=new Date('2026-11-02T17:00:00Z');
assert.equal(vietnamDate(tuesday),'2026-11-03');
assert.deepEqual(attendanceReminders(rows,owner,tuesday).due.map(x=>x.record.id),['B','A']);
assert.deepEqual(attendanceReminders(rows,owner,tuesday).unknown.map(x=>x.id),['E']);
const staff={permissions:{attendance_manage:true},classIds:['A']};assert.deepEqual(attendanceReminders(rows,staff,tuesday).due.map(x=>x.record.id),['A']);
assert.equal(attendanceReminders(rows,{...staff,permissions:{}},tuesday).due.length,0);
const session={kind:'attendance',id:'2026-11-03_A',data:{status:'draft'}};
assert.equal(attendanceReminders([...rows,session],staff,tuesday).due[0].status,'draft');
assert.equal(attendanceReminders([...rows,{...session,data:{status:'final'}}],staff,tuesday).due[0].status,'done');
assert.equal(attendanceReminders([...rows,{...session,data:{status:'final',deleted:true}}],staff,tuesday).due[0].status,'missing');
assert.equal(attendanceReminders([cls('Sunday','CN')],owner,new Date('2026-11-07T17:01:00Z')).due.length,1);
assert.equal(attendanceReminders(rows,owner,new Date('2026-11-03T17:00:00Z')).due[0].record.id,'C');
console.log('PASS: Vietnamese weekday formats, invalid schedules, VN midnight/Sunday rollover, class scope and permissions, deleted classes/sessions, draft/final states and time sorting.');
